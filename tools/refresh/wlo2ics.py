def warn(msg):
    print("%s: warning: %s" % (PROG, msg), file=sys.stderr)


def clean_text(raw):
    """Strip tags/entities from an HTML fragment -> plain text."""
    t = re.sub(r"<[^>]+>", "", raw)
    t = html.unescape(t)
    t = t.replace("\xa0", " ").replace("&nbsp;", " ")
    return t.strip()


def strip_titles(name):
    """'dr hab. inż. Kowalski Jan, WAT' -> 'Kowalski Jan'.

    Titles/ranks/affiliations are stripped token-wise; dots and brackets
    also split ('dr hab.' -> dr + hab) since the planner is
    inconsistent about spaces. A trailing ", ..." affiliation
    ('Kowalski Jan, WAT') is cut first.
    """
    name = name.split(",")[0]
    toks = [t for t in re.split(r"[\s.()]+", name) if t]
    while toks and toks[0].lower() in TITLE_WORDS:
        toks.pop(0)
    return " ".join(toks)


def swap_name(name):
    """'Kowalski Jan' -> 'Jan Kowalski' (firstname is last token)."""
    parts = name.split()
    if len(parts) >= 2:
        return parts[-1] + " " + " ".join(parts[:-1])
    return name


def subject_color(subject):
    palette = ["#FFB3BA", "#FFDFBA", "#FFFFBA", "#BAFFC9", "#BAE1FF",
               "#D5BAFF", "#FFBAF3", "#FFE4B5", "#B5EAD7", "#C7CEEA",
               "#E2F0CB", "#FFDAC1", "#BDE0FE", "#FFC6FF", "#A0E7E5"]
    idx = int(hashlib.sha1(subject.encode("utf-8")).hexdigest(), 16) % len(palette)
    return palette[idx]


def esc(text):
    return (text.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,")
                .replace("\n", "\\n").replace("\r", ""))


def fold_line(line):
    out = []
    cur, cur_len, limit = "", 0, 75
    for ch in line:
        blen = len(ch.encode("utf-8"))
        if cur_len + blen > limit:
            out.append(cur)
            cur, cur_len, limit = "", 0, 74
        cur += ch
        cur_len += blen
    out.append(cur)
    return "\r\n ".join(out)


TD_RE = re.compile(r"<td((?:\"[^\"]*\"|[^>])*)>(.*?)</td>", re.I | re.S)


def split_cells(row):
    """Split a <tr> into [(attrs, inner)] cells. Quote-aware: raw server
    pages carry unescaped "<P ...>" inside mergeWith="...", so a naive
    [^>]* would split inside the attribute."""
    return TD_RE.findall(row)


SETTLEMENT_RE = re.compile(
    r"^([A-Za-z\u0100-\u017f\ufffd./]+)\s+(\d+)\s*$")
MULTI_SETTLEMENT_RE = re.compile(
    r"^(.+?)\s+(\d+)\s*$")
SUBJECT_HEAD_RE = re.compile(r"^([^(]*)\((.*)\)\s*$")
DATE_RE = re.compile(r"^(\d\d?)\s+([XVI]+)$")
SLOT_RE = re.compile(r"^(\d+)\s*-\s*(\d+)$")
DAY_RE = re.compile(r"^(pon|wt|(\ufffd|\u015b)r|czw|pt|sob|niedz)\.$", re.I)
UPDATE_RE = re.compile(r"Data aktualizacji:\s*(\d+)\.(\d+)\.(\d+)")
SHORT_SHAPE_RE = re.compile(r"^[A-Za-z\u0100-\u017f\ufffd. ]+$")


def repair_type(typ):
    """A damaged/non-ASCII char in the (type) position can only be 'ć'."""
    if typ and not typ.isascii():
        return "\u0107"
    return typ


def parse_page(path):
    with open(path, "rb") as f:
        raw = f.read()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        text = raw.decode("windows-1250")
        warn("input is not UTF-8; decoded as windows-1250")
    damaged = text.count("\ufffd")
    if damaged:
        warn("input holds %d U+FFFD damage markers "
             "(browser-saved with wrong encoding); names may be degraded, "
             "see header comment for a clean-save recipe" % damaged)

    rows = re.findall(r"<tr[^>]*>(.*?)</tr>", text, re.I | re.S)
    date_blocks = []   # (day, [date-or-None x N])
    week_rows = []     # (block_index, slot, [cell-html x N])
    legends = []       # (short, full-or-None) in document order
    split = [split_cells(r) for r in rows]
    # The IOE site prints a transposed grid: every row starts with the
    # weekday and the lesson rows carry the time slot in the second cell
    # ([day, slot, spacer, week cells..., legend, full]), while each
    # weekday block opens with its own date strip in the same shape.
    # Standard pages never pair a weekday with a slot this way, so one
    # such row marks the whole page.
    transposed = any(
        len(c) >= 20 and DAY_RE.match(clean_text(c[0][1]))
        and SLOT_RE.match(clean_text(c[1][1])) for c in split)
    day_strips = {}
    for cells in split:
        if len(cells) < 20:
            # short rows carry no week columns, but real legend entries hide
            # in them (WML parks lecturer aliases there): harvest every pair.
            # Padding rows have no mergeWith cell and stay skipped.
            for a, inner in cells:
                if "mergewith" in a.lower():
                    leg = legend_pair((a, inner))
                    if leg:
                        legends.append(leg)
            continue
        first = clean_text(cells[0][1])
        # the mergeWith legend cell: last cell carrying the attribute;
        # week columns run between the label and the legend (WEL pages
        # omit trailing empty week columns, so widths vary)
        mi = max((i for i, (a, _) in enumerate(cells)
                  if "mergewith" in a.lower()), default=None)
        if transposed:
            # [day, slot-or-blank, spacer, week cells..., legend, full];
            # the week's dates run from the third cell, and each weekday
            # block opens with its own date strip in the same shape.
            leg = legend_pair(cells[mi]) if mi is not None else None
            if leg:
                legends.append(leg)
            if not DAY_RE.match(first):
                continue  # legend-only row: no day, no dates, no lessons
            mslot = SLOT_RE.match(clean_text(cells[1][1]))
            if mslot:
                bi = day_strips.get(first)
                if bi is None:
                    warn("transposed lesson row before its date strip; "
                         "row skipped")
                    continue
                week_rows.append((bi, "%s-%s" % mslot.groups(),
                                  [c for _, c in cells[3:mi]]))
                continue
            dates = []
            for _, c in cells[3:mi]:
                m = DATE_RE.match(clean_text(c))
                if m and m.group(2) in ROMAN_MONTH:
                    dates.append((int(m.group(1)), ROMAN_MONTH[m.group(2)]))
                else:
                    dates.append(None)
            day_strips[first] = len(date_blocks)
            date_blocks.append((first, dates))
            continue
        mslot = SLOT_RE.match(first)
        if mslot:
            if mi is None:
                continue
            slot = "%s-%s" % mslot.groups()
            week_rows.append((len(date_blocks) - 1, slot,
                              [c for _, c in cells[1:mi]]))
            leg = legend_pair(cells[mi])
            if leg:
                legends.append(leg)
        else:
            # date-header row (day label may carry U+FFFD damage, e.g. środa)
            if not DAY_RE.match(first):
                # warn only if the row carries dates or lessons; pure
                # legend/padding rows (military pages add dozens) are silent
                has_content = False
                for _, c in cells[1:]:
                    t = clean_text(c)
                    if DATE_RE.match(t):
                        has_content = True
                        break
                    segs = re.findall(r"<font[^>]*>(.*?)</font>", c,
                                      re.I | re.S)
                    if len(segs) >= 3 and clean_text(segs[0]):
                        hm0 = SUBJECT_HEAD_RE.match(clean_text(segs[0]))
                        if hm0 or (len(segs) == 3 and clean_text(segs[1])):
                            has_content = True
                            break
                if has_content:
                    warn("unrecognized long row starting %r; "
                         "treating as date row" % first[:20])
                # rows without dates still append (empty block) so block
                # indexing of any following week rows stays aligned
            dates = []
            for _, c in cells[2:mi]:
                m = DATE_RE.match(clean_text(c))
                if m and m.group(2) in ROMAN_MONTH:
                    dates.append((int(m.group(1)), ROMAN_MONTH[m.group(2)]))
                else:
                    dates.append(None)
            date_blocks.append((first, dates))
            if mi is not None:
                leg = legend_pair(cells[mi])
                if leg:
                    legends.append(leg)
    m = UPDATE_RE.search(clean_text(text))
    updated = (int(m.group(1)), int(m.group(2)), int(m.group(3))) if m else None
    return date_blocks, week_rows, legends, updated


def legend_pair(merge_cell, _full_cell=None):
    attr, inner = merge_cell
    m = re.search(r"mergewith\s*=\s*\"([^\"]*)\"", attr, re.I)
    if not m:
        return None
    payload = html.unescape(m.group(1))
    # WLO/WEL payloads end with a legend number ("...</P>12"); WIM
    # payloads carry the bare "<P>name</P>" (positional order still pairs
    # settlements to subjects)
    pm = re.search(r"<P[^>]*>(.*?)</P>\s*\d*\s*$", payload, re.I | re.S)
    full = clean_text(pm.group(1)) if pm else None
    short = clean_text(inner)
    if not short:
        return None
    return (short, full)


def looks_like_person(full):
    """Settlement full names are people ('dr hab. inż. Kowalski Jan'); subject full names are
    not. A leading title is the distinguisher (no subject starts with one); dots and brackets
    inside the name do not count (subjects like 'Język obcy (II) ...' are not people)."""
    if not full:
        return False
    toks = [t for t in re.split(r"[\s.()]+", full.split(",")[0]) if t]
    if not toks or toks[0].lower() not in TITLE_WORDS:
        return False
    stripped = strip_titles(full)
    return bool(re.search(r"[A-Za-z\u0100-\u017f]", stripped))


# Academic and military titles only. The wider TITLE_WORDS also holds words like "st" and "wat",
# which open real room names ("ST.nr 1(PWC2)"), so they cannot decide whether a room is a person.
ROOM_TITLES = {"dr", "hab", "prof", "inż", "inz", "mgr", "lic", "płk", "ppłk", "mjr", "kpt", "por",
               "ppor", "gen", "bryg", "rez", "ucz"}


# A lecturer alias the converter failed to split off the room: initial(s) glued to a capitalised surname
# ('AKowalski'). A real room never has two capitals followed by a run of lowercase letters ('Teams', '314 S',
# 'ST.nr 1(PWC2)'); U+FFFD stands in for a letter lost to the page's code page.
_UP, _LOW = 'A-ZĄĆĘŁŃÓŚŹŻ', 'a-ząćęłńóśźż'
ALIAS_RE = re.compile(rf'[{_UP}�]{{1,2}}[{_UP}][{_LOW}�]{{3,}}(?:-[{_UP}][{_LOW}�]+)?')


def names_person(part):
    """True for 'dr inż. Kowalski Jan' (leading title(s) followed by a capitalised name) and for a bare
    lecturer alias such as 'AKowalski'."""
    if ALIAS_RE.fullmatch(part.strip()):
        return True
    toks = [t for t in re.split(r"[\s.()]+", part.strip()) if t]
    i = 0
    while i < len(toks) and toks[i].lower() in ROOM_TITLES:
        i += 1
    return 0 < i < len(toks) and toks[i][0].isalpha() and toks[i][0].isupper()


def public_room(room):
    """The room text that may be published: every ';'/','-separated part that names a person is
    dropped, so a misparsed cell can never put staff into a calendar. A room without such a part
    is returned unchanged."""
    parts = [p.strip() for p in re.split(r"[;,]", room or "")]
    if not any(p and names_person(p) for p in parts):
        return room
    return ";".join(p for p in parts if p and not names_person(p))


def build_tables(legends):
    """Legends -> subject full names + (subject, type) -> [lecturers].

    Settlement rows always directly follow their subject row, in legend
    order. Settlement shorts are 'w 44' / 'Zp/lab. 2' (single token +
    hours) or, on WIM pages, multi-word like 'Zp. ćw 2'; they are told
    apart from subject shorts ('Mt 1', 'SBN - TNSS') by the full name:
    settlements name a person, subjects do not.
    One (subject, type) may settle on several lecturers (split lab
    groups); the list keeps them all, in legend order.
    Lecturers come WITH titles on the site; output uses plain
    "Firstname Surname" (titles stripped, surname-first input swapped).
    """
    subjects = {}
    subj_type_lect = {}

    def add_lect(key, full):
        stripped = strip_titles(full)
        if not re.search(r"[A-Za-z\u0100-\u017f]", stripped):
            return
        lect = swap_name(" ".join(stripped.split()))
        subj_type_lect.setdefault(key, [])
        if lect not in subj_type_lect[key]:
            subj_type_lect[key].append(lect)

    current = None
    for short, full in legends:
        sm = SETTLEMENT_RE.match(short)
        person = looks_like_person(full)
        if sm and current is not None and (person or not full):
            # 'w 44' (+ optional lecturer; hour counts may stand alone)
            if full and person:
                add_lect((current, repair_type(sm.group(1))), full)
            elif full is None:
                subj_type_lect.setdefault(
                    (current, repair_type(sm.group(1))), [])
        elif current is not None and person and not sm:
            # WIM multi-word settlement: 'Zp. ćw 2' -> type 'Zp. ćw'
            mm = MULTI_SETTLEMENT_RE.match(short)
            if mm:
                add_lect((current, repair_type(mm.group(1).strip())), full)
            else:
                current = short
                subjects[short] = full or short
        else:
            current = short
            subjects[short] = full or short
    return subjects, subj_type_lect


# a groups-list token: uppercase-led id with digits (WLO26AX1S1,
# WME22MT1S0-War); rooms ('126 K', '42/ 20', 'AW 3/038') never match
GROUP_TOKEN_RE = re.compile(r"^[A-Z]{2,}\d[A-Z0-9_-]*$")


def looks_like_groups(text):
    return any(GROUP_TOKEN_RE.match(tok.strip())
               for tok in text.split(";") if tok.strip())


def learn_shorts(week_rows, subj_type_lect, resolve):
    """(subject, type) cells carry lecturer short(s) -> map short to names.

    Lecturer slot is segs[2] in WLO 4-seg cells [SUBJ, groups, short,
    room] and in WIM 3/4-seg cells [SUBJ, room, short(, note)] (the two
    are told apart by whether segs[1] is a groups list); the slot may
    hold several ';'-separated shorts.
    """
    candidates = {}

    def consider(subj, typ, slot):
        key = resolve(subj)
        if key is None:
            return
        for part in re.split(r"[;,]", slot):
            cand = part.strip()
            if not cand or not SHORT_SHAPE_RE.match(cand):
                continue
            if "/" in cand or any(ch.isdigit() for ch in cand):
                continue
            if len(cand) > 12:
                continue
            typ_r = repair_type(typ.strip())
            candidates.setdefault((key, typ_r), set()).add(cand)

    for _, _, cells in week_rows:
        for c in cells:
            segs = [clean_text(s) for s in
                    re.findall(r"<font[^>]*>(.*?)</font>", c, re.I | re.S)]
            while len(segs) > 4 and re.match(r"^\d+\s*%$", segs[0]):
                segs.pop(0)
            if not segs:
                continue
            hm = SUBJECT_HEAD_RE.match(segs[0])
            if not hm:
                continue
            if len(segs) == 4 and looks_like_groups(segs[1]):
                consider(hm.group(1).strip(), hm.group(2), segs[2])
            elif len(segs) in (3, 4) and not looks_like_groups(segs[1]):
                consider(hm.group(1).strip(), hm.group(2), segs[2])
    short_map = {}
    for key, cands in candidates.items():
        if key not in subj_type_lect or not subj_type_lect[key]:
            continue
        if len(cands) == 1:
            short_map[next(iter(cands))] = subj_type_lect[key]
        else:
            warn("shorts %s for %s %s ambiguous; using settlement lecturer"
                 % (sorted(cands), key[0], key[1]))
    return short_map


def match_alias(slot_text, alias):
    """A WML lecturer slot -> [names], best effort (parse intermediate only).

    Cells truncate aliases ('Kowalski' -> 'Kowa'), so an exact hit falls back
    to a unique prefix hit; ';'-separated slots resolve part-wise. Unknown
    shorts give []: the calendar never names staff either way.
    """
    out = []
    for part in re.split(r"[;,]", slot_text):
        p = part.strip()
        if not p:
            continue
        if p in alias:
            cands = [p]
        else:
            cands = [a for a in alias if a.startswith(p)]
            if len(cands) != 1:
                continue
        out.extend(x for x in alias[cands[0]] if x not in out)
    return out


def parse_lessons(date_blocks, week_rows, subjects, subj_type_lect,
                  short_map, group, base_year, resolve, lect_alias=None,
                  ioe=False):
    lessons = []
    type_warned = set()
    subj_warned = set()
    short_warned = set()
    for bi, slot, cells in week_rows:
        if slot not in SLOT_TIMES:
            warn("no time mapping for slot %s; row skipped" % slot)
            continue
        if bi < 0 or bi >= len(date_blocks):
            warn("week row outside any day block; skipped")
            continue
        dates = date_blocks[bi][1]
        for wi, c in enumerate(cells):
            if wi >= len(dates) or dates[wi] is None:
                continue
            d, m = dates[wi]
            try:
                dt = datetime.date(base_year + (0 if m >= 10 else 1), m, d)
            except ValueError:
                warn("bad date %d.%d; skipped" % (d, m))
                continue
            segs = [clean_text(s) for s in
                    re.findall(r"<font[^>]*>(.*?)</font>", c, re.I | re.S)]
            # leading share note ("50%" = partial-group class): strip it
            # but keep it for the DESCRIPTION
            shares = []
            while len(segs) > 3 and re.match(r"^\d+\s*%$", segs[0]):
                shares.append(segs.pop(0))
            if not segs or not segs[0]:
                continue
            hm = SUBJECT_HEAD_RE.match(segs[0])
            groups, lect_slot, room, notes = [], None, "", []
            positional = False
            lects_pre, wel = None, False
            wml = lect_alias is not None
            if hm:
                subj = hm.group(1).strip()
                typ = repair_type(hm.group(2).strip())
                if len(segs) >= 4 and looks_like_groups(segs[1]):
                    # WLO cell: SUBJ(type) / groups / lecturer / room
                    groups = [g.strip() for g in segs[1].split(";")
                              if g.strip()]
                    if group and group not in groups:
                        continue
                    lect_slot, room = segs[2], segs[3]
                    notes = segs[4:]
                    positional = True
                elif len(segs) >= 4:
                    # WIM cell: SUBJ(type) / room / lecturer(s) / note
                    room, lect_slot, notes = segs[1], segs[2], segs[3:]
                    positional = True
                elif len(segs) == 3 and looks_like_groups(segs[1]):
                    # WLO short cell: SUBJ(type) / groups / room; rarely
                    # the planner puts the lecturer alias in the room
                    # slot (e.g. WF classes "MKubajka")
                    groups = [g.strip() for g in segs[1].split(";")
                              if g.strip()]
                    if group and group not in groups:
                        continue
                    third = segs[2]
                    if third in short_map or (
                            re.match(r"^[A-Za-z\u0100-\u017f\ufffd.()-]+$",
                                     third)
                            and re.search(
                                r"[a-z\u0105\u0107\u0119\u0142\u0144\u00f3"
                                r"\u015b\u017a\u017c]", third)
                            and subj_type_lect.get((resolve(subj), typ))):
                        lect_slot, room = third, ""
                    else:
                        room = third
                elif len(segs) == 3:
                    # WIM short cell: SUBJ(type) / room / lecturer-or-room
                    room, lect_slot = segs[1], segs[2]
                elif len(segs) == 2:
                    # subject + room only (language classes etc.)
                    room = segs[1]
                # len == 1: subject alone
            elif wml and len(segs) == 4:
                # WML cell: lecturer / room / SUBJECT / type (the page shows
                # its own plan; lecturer aliases may be truncated in cells)
                lect_slot, room, subj, typ = (s.strip() for s in segs)
                typ = repair_type(typ)
                if not subj or not typ:
                    continue
                groups = []
            elif (wml and len(segs) == 3
                    and resolve(segs[1].strip()) is not None):
                # WML short cell: room-or-lecturer / SUBJECT / type
                maybe = segs[0].strip()
                if match_alias(maybe, lect_alias):
                    lect_slot = maybe
                else:
                    room = maybe
                subj, typ = segs[1].strip(), repair_type(segs[2].strip())
                if not subj or not typ:
                    continue
                groups = []
            else:
                if ioe and len(segs) == 4:
                    # IOE cell: SUBJ / type / room / lecturer alias. The
                    # alias is a parse intermediate only (the calendar
                    # never names staff), so it is dropped, not resolved.
                    subj = segs[0].strip()
                    typ = repair_type(segs[1].strip())
                    room = segs[2].strip()
                    if looks_like_person(room):
                        room = ""  # a misplaced alias, never publish it
                    lects_pre, groups, wel = None, [], True
                elif ioe and len(segs) == 3:
                    # IOE short cell: SUBJ / type / room-or-alias. A token
                    # without digits is an alias, not a room: drop it.
                    subj = segs[0].strip()
                    typ = repair_type(segs[1].strip())
                    third = segs[2].strip()
                    room = (third if re.search(r"\d", third)
                            or third == "aE" else "")
                    lects_pre, groups, wel = None, [], True
                elif ioe:
                    # IOE bare cell: a subject alone (e.g. 'Ing').
                    subj, typ, room = segs[0].strip(), "", ""
                    lects_pre, groups, wel = None, [], True
                else:
                    # WEL-style cell: SUBJ / type / room (the page shows its
                    # own plan; no group or lecturer lines in cells)
                    subj = segs[0].strip()
                    typ = repair_type(segs[1].strip()) if len(segs) > 1 else ""
                    if not subj or not typ:
                        continue
                    room = segs[-1] if len(segs) >= 3 else ""
                    if len(segs) > 3 and segs[2] in short_map:
                        lects_pre = list(short_map[segs[2]])
                    else:
                        lects_pre = None
                    groups = []
                    wel = True
            if not subj or (not typ and not ioe):
                continue
            subj_key = resolve(subj)
            if subj_key is None:
                if subj not in subj_warned:
                    warn("no legend entry for subject %r; using short" % subj)
                    subj_warned.add(subj)
                full = subj
                subj_key = subj
            else:
                full = subjects[subj_key]
            if (wml or ioe) and looks_like_person(full):
                warn("subject %r resolves to staff (%r); lesson skipped" % (subj, full))
                continue
            if typ not in TYPE_LABELS and typ not in type_warned:
                warn("unknown type code %r; using it verbatim" % typ)
                type_warned.add(typ)
            label = TYPE_LABELS.get(typ, typ or "Zajęcia")
            tstart, tend = SLOT_TIMES[slot]
            settle = list(subj_type_lect.get((subj_key, typ), []))

            def resolve_slot(slot_text, positional=False):
                """Lecturer slot -> ([names], room_extra or None).

                positional=True for 4-seg cells, where segs[2] is
                structurally the lecturer slot (WLO [SUBJ, groups,
                lecturer, room], WIM [SUBJ, room, lecturer, note]): trust
                the position, only '/' diverts to room-extra. Otherwise
                (3-seg ambiguous slot) apply shape guards too, since the
                slot may hold a room instead.
                """
                if slot_text in short_map:
                    return list(short_map[slot_text]), None
                if "/" in slot_text:
                    return settle, slot_text
                parts = [p.strip() for p in re.split(r"[;,]", slot_text)
                         if p.strip()]
                if len(parts) > 1:
                    out = []
                    for p in parts:
                        if p in short_map:
                            out.extend(x for x in short_map[p]
                                       if x not in out)
                        elif "/" in p or any(ch.isdigit() for ch in p):
                            return settle, slot_text
                    if out:
                        return out, None
                    if settle:
                        return settle, None
                    for p in parts:
                        if p not in short_warned:
                            warn("unresolved lecturer short %r for %s (%s)"
                                 % (p, subj, dt.isoformat()))
                            short_warned.add(p)
                    return parts, None
                if not positional and (
                        len(slot_text) > 12
                        or any(ch.isdigit() for ch in slot_text)
                        or not re.search(
                            r"[a-z\u0105\u0107\u0119\u0142\u0144\u00f3"
                            r"\u015b\u017a\u017c]", slot_text)):
                    # room-like token in the lecturer slot
                    return settle, slot_text
                if settle:
                    return settle, None
                if slot_text not in short_warned:
                    warn("unresolved lecturer short %r for %s (%s)"
                         % (slot_text, subj, dt.isoformat()))
                    short_warned.add(slot_text)
                return [slot_text], None

            lects = []
            if wel and lects_pre is not None:
                lects = lects_pre
            elif wel:
                lects = settle
            elif wml and lect_slot:
                lects = match_alias(lect_slot, lect_alias)
                if not lects and lect_slot not in short_warned:
                    warn("unresolved lecturer alias %r for %s (%s)"
                         % (lect_slot, subj, dt.isoformat()))
                    short_warned.add(lect_slot)
            elif lect_slot is None:
                lects = settle
            else:
                lects, extra = resolve_slot(lect_slot, positional)
                if extra is not None:
                    room = extra if not room else extra + "; " + room
            shares = shares + notes
            lessons.append({
                "date": dt.strftime("%Y%m%d"), "start": tstart, "end": tend,
                "subject": full, "type": label, "room": room,
                "contacts": lects, "groups": groups, "shares": shares,
            })
    return lessons


def build_ics(lessons, group, period, updated, generated, faculty="wlo"):
    fac = faculty.upper()
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//PlanWAT//%s//PL" % fac,
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        "X-WR-CALNAME:Plan zaj\u0119\u0107 %s" % group,
        "X-WR-CALDESC:Nieoficjalny plan zaj\u0119\u0107 %s (%s Plansoft)"
        % (group, fac),
        "X-WR-TIMEZONE:Europe/Warsaw",
        "REFRESH-INTERVAL;VALUE=DURATION:PT12H",
        "X-PUBLISHED-TTL:PT12H",
        "X-PLAN-GROUP:%s" % group,
        "X-PLAN-SOURCE:%s-plansoft" % faculty,
    ]
    if period:
        lines.append("X-PLAN-PERIOD:%s" % period)
    if updated:
        lines.append("X-PLAN-UPDATED:%04d%02d%02d" % (updated[2], updated[1],
                                                     updated[0]))
    if lessons:
        ds = sorted(l["date"] for l in lessons)
        lines.append("X-PLAN-SEMESTER-START:%s" % ds[0])
        lines.append("X-PLAN-SEMESTER-END:%s" % ds[-1])
    lines.append("X-PLAN-GENERATED:%s" % generated.strftime("%Y%m%d"))
    lines.extend(VTIMEZONE.split("\n"))

    lessons.sort(key=lambda l: (l["date"], l["start"]))
    used = set()
    nevents = 0
    for lesson in lessons:
        base_uid = "%sT%s-%s@%s" % (lesson["date"], lesson["start"],
                                    group.lower(), faculty)
        uid, n = base_uid, 2
        while uid in used:
            uid = "%s-%d" % (base_uid, n)
            n += 1
        used.add(uid)
        if uid != base_uid:
            warn("duplicate slot %s %s; disambiguated UID %s"
                 % (lesson["date"], lesson["start"], uid))
        lines.append("BEGIN:VEVENT")
        lines.append("UID:%s" % uid)
        lines.append("DTSTAMP:%sT000000Z" % generated.strftime("%Y%m%d"))
        lines.append("DTSTART;TZID=Europe/Warsaw:%sT%s00"
                     % (lesson["date"], lesson["start"]))
        lines.append("DTEND;TZID=Europe/Warsaw:%sT%s00"
                     % (lesson["date"], lesson["end"]))
        lines.append("SUMMARY:%s" % esc(lesson["subject"]))
        lines.append("CATEGORIES:%s" % esc(lesson["type"]))
        room = public_room(lesson["room"])
        if room:
            lines.append("LOCATION:%s" % esc(room))
        desc = lesson["type"]
        if lesson.get("shares"):
            desc += "\nUwaga: %s" % " ".join(lesson["shares"])
        if len(lesson["groups"]) > 1:
            desc += "\nGrupy: %s" % ", ".join(lesson["groups"])
        lines.append("DESCRIPTION:%s" % esc(desc))
        lines.append("X-PLAN-COLOR:%s" % subject_color(lesson["subject"]))
        lines.append("END:VEVENT")
        nevents += 1
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n", nevents


def main(argv):
    import argparse
    ap = argparse.ArgumentParser(
        description="Convert a saved WLO Plansoft page to ICS (stdlib only).")
    ap.add_argument("input", help="saved group/lecturer .htm page")
    ap.add_argument("-o", "--output", required=True, help="output .ics path")
    ap.add_argument("--grupa", default=None,
                    help="group id filter (default: from filename)")
    ap.add_argument("--period", default=None,
                    help="semester label, e.g. 'WLO zima 2026/2027'")
    ap.add_argument("--faculty", default=None,
                    help="faculty code for UIDs/headers "
                    "(default: WLO*/WEL* filename prefix, else 'wlo')")
    ap.add_argument("--year", type=int, default=None,
                    help="academic year the plan starts in, e.g. 2026 for "
                    "2026/27 (default: from the update footer)")
    ap.add_argument("--code", default=None,
                    help="group code written to the calendar and used for its "
                    "UIDs (default: the page's own group id)")
    args = ap.parse_args(argv)
    stem = os.path.splitext(os.path.basename(args.input))[0]
    faculty = (args.faculty or ("wel" if stem.startswith("WEL")
                                else "wlo")).lower()
    group = args.grupa or stem
    gfilter = group if re.match(r"^[A-Z0-9]+$", group) else None
    if gfilter is None:
        warn("page %r is not a group page; including all lessons" % stem)
    date_blocks, week_rows, legends, updated = parse_page(args.input)
    subjects, subj_type_lect = build_tables(legends)

    resolved_cache = {}

    def resolve(subj):
        if subj in resolved_cache:
            return resolved_cache[subj]
        if subj in subjects:
            resolved_cache[subj] = subj
            return subj
        cands = [k for k in subjects if k.startswith(subj)]
        if len(cands) == 1:
            resolved_cache[subj] = cands[0]
            return cands[0]
        resolved_cache[subj] = None
        return None

    short_map = learn_shorts(week_rows, subj_type_lect, resolve)
    lect_alias = None
    if faculty == "wml":
        # WML legends name lecturers with bare aliases (no hour settlements):
        # alias -> [names], resolved data-driven like everything else here.
        # Names are parse intermediates only (the calendar never names staff).
        lect_alias = {}
        for short, full in legends:
            if full and looks_like_person(full):
                name = swap_name(" ".join(strip_titles(full).split()))
                if re.search(r"[A-Za-z\u0100-\u017f]", name):
                    lect_alias.setdefault(short, [])
                    if name not in lect_alias[short]:
                        lect_alias[short].append(name)
    if args.year:
        base_year = args.year
    elif updated and updated[1] >= 9:
        base_year = updated[2]
    elif updated:
        base_year = updated[2] - 1
    else:
        warn("no update footer; assuming winter term of current year")
        now = datetime.date.today()
        base_year = now.year if now.month >= 9 else now.year - 1
    lessons = parse_lessons(date_blocks, week_rows, subjects,
                            subj_type_lect, short_map, gfilter, base_year,
                            resolve, lect_alias, ioe=(faculty == "ioe"))
    ics, n = build_ics(lessons, args.code or group, args.period, updated,
                       datetime.date.today(), faculty)
    with open(args.output, "w", encoding="utf-8", newline="") as f:
        f.write(ics)
    print("%d lessons kept, %d events written (%s)"
          % (len(lessons), n, group), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1:])