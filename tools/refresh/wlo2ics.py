#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""wlo2ics.py - convert a saved WLO/WEL Plansoft timetable page (.htm) to ICS.
Stdlib only. Usage:
    python wlo2ics.py WLO26AX1S1.htm -o plan-WLO26AX1S1.ics [--grupa ID]
                    [--period "WLO zima 2026/2027"] [--faculty wlo]

Two export variants are handled (same engine):
  * WLO: lesson cell = SUBJECT(type) / groups / lecturer-short / room,
    fixed 22 week columns, "Data aktualizacji" footer for the year.
  * WEL: lesson cell = SUBJECT / type / room (the page shows its own plan;
    lecturers come only from settlements), week rows omit trailing empty
    columns (left-aligned to the date row), no footer date (year falls back
    to the current-date rule with a warning).
  * WIM: lesson cell = SUBJECT(type) / room / lecturer-short [/ note],
    39 week columns spanning winter AND summer semesters (Sept-June),
    windows-1250 bytes, legend payloads without trailing numbers,
    multi-word settlement types ('Zp. ćw 2'), ';'-separated lecturer
    slots and subgroup notes ('Podgrupa 1'). Subjects vs settlements are
    told apart by the full name (settlements name a person).
  * WML: lesson cell = lecturer-short / room / SUBJECT / type (the page
    shows its own plan; cells truncate aliases, e.g. 'Kowalski' -> 'Kowa',
    while the legend carries bare aliases without hour settlements).

Mechanism of the source site (https://wlo.wat.edu.pl/planzajec/zima/):
  * index.xml catalogues group pages (<gro>), lecturer pages (<lec>) and
    rooms (<res>). Each group page is ONE static semester grid, generated by
    Plansoft.org: weekday blocks (pon..niedz) x 7 lesson slots (1-2 .. 13-14)
    x ~21 explicit date columns ("05 X" .. "22 II").
  * A lesson cell holds 4 <font> segments:
        SUBJECT-SHORT(type) / groups;... / lecturer-short / room
    or 3 segments (no lecturer: language classes, info meetings):
        SUBJECT-SHORT(type) / groups;... / room
  * The two right-hand columns of every row form a legend: the cell with a
    mergeWith="<P>Full name</P>N" attribute gives the expansion of the
    visible short code. Two legend kinds, distinguished by the SHORT:
      - subject short  -> full subject name  (e.g. "Lg" -> "Logika"),
      - "w 20"/"E 2"   -> lecturer hour settlement for the preceding
        subject, i.e. (subject, type) -> lecturer full name WITH title.
    Settlement rows always directly follow their subject row, in legend
    number order.
  * Lecturer shorts ("Sku", "TK", "Ko. W.", "D-SM", ...) are planner-assigned
    aliases. They are resolved data-driven: for each (subject, type) the
    settlement names the lecturer, and the cells using that (subject, type)
    carry (almost always) exactly one distinct short -> mapping learned.
  * Lecturer names and titles are never written to the calendar: it carries
    no personal data of staff (no CONTACT line, no instructor line).
  * Slot -> clock time is NOT printed on the page. SLOT_TIMES below reuses
    the WAT-wide standard (same 7 pairs as the WCY planzajec blocks).
    XXX verify against a real WLO lesson if they ever publish hours.
  * The page carries no year; it is derived from the "Data aktualizacji"
    footer (Oct+ -> that year; earlier -> previous year; Oct-Dec map to it,
    Jan-Sep to the next year).
  * Server bytes are windows-1250 despite the lying utf-8 META tag; a
    browser "Save page" therefore stores U+FFFD damage for Polish chars.
    Clean input: in the page console run
      copy(new TextDecoder('windows-1250').decode(
        new Uint8Array(await (await fetch(location.href)).arrayBuffer())))
    and paste into the .htm file. Damaged files still parse (a warning
    counts the replacements); a damaged single char in the (type) position
    can only be "ć" and is repaired.
"""

